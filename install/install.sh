#!/usr/bin/env bash
#
# Install the traffic-reporting stack on the swanpan droplet.
#
# Idempotent: safe to re-run. Every step checks before acting, so running this
# on an already-configured box changes nothing.
#
# Reproduces:
#   - Cloudflare real_ip so logs record visitors, not edge addresses
#   - a log_format carrying $request_time and $cf_ipcountry
#   - the swanpan-traffic job and its 10-minute timer
#   - the analytics.limeyeti.com vhost behind basic auth
#
# Deliberately does NOT:
#   - touch the product vhosts beyond the access_log format (see step 5)
#   - enable a certificate for a domain you have not pointed at this host
#
# Run as root from the repo root: sudo bash install/install.sh

set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Run as root" >&2; exit 1; }

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
DOMAIN=analytics.limeyeti.com
AUTH_USER=hoyoul
TRAFFIC_DIR=/var/www/traffic
STATE_DIR=/var/lib/swanpan-traffic
HTPASSWD=/etc/nginx/.htpasswd-limeyeti

say() { printf '\n== %s\n' "$*"; }

say "1. Install goaccess"
if command -v goaccess >/dev/null; then
  echo "   already installed: $(goaccess --version | head -1)"
else
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq goaccess
  echo "   installed: $(goaccess --version | head -1)"
fi

say "2. Cloudflare real_ip"
# Fetched live rather than hardcoded: Cloudflare's ranges change, and a stale
# list means visitors get logged as edge addresses again.
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
curl -fsS https://www.cloudflare.com/ips-v4 -o "$TMP/v4"
curl -fsS https://www.cloudflare.com/ips-v6 -o "$TMP/v6"
v4=$(grep -c . "$TMP/v4"); v6=$(grep -c . "$TMP/v6")
echo "   $v4 IPv4 + $v6 IPv6 ranges"

{
  echo "# Cloudflare edge ranges, so nginx logs real visitor IPs instead of"
  echo "# Cloudflare's. Generated by install/install.sh -- do not edit by hand."
  echo "#"
  echo "# CF-Connecting-IP is set by Cloudflare and overwritten on every request,"
  echo "# so a client cannot forge it."
  while read -r r; do [[ -n $r ]] && echo "set_real_ip_from $r;"; done < "$TMP/v4"
  # NOTE: these files have no trailing newline. Without an explicit newline
  # between chunks, the last range concatenates with the next line.
  printf '\n'
  while read -r r; do [[ -n $r ]] && echo "set_real_ip_from $r;"; done < "$TMP/v6"
  echo
  echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-realip.conf

say "3. Log format with request time and country"
install -m 644 "$REPO/nginx/swanpan-logformat.conf" /etc/nginx/conf.d/swanpan-logformat.conf
install -m 644 "$REPO/nginx/swanpan-cfcountry.conf" /etc/nginx/conf.d/swanpan-cfcountry.conf
echo "   installed"

say "4. Report directories"
# 750 + www-data: these pages list visitor IPs. Not world-readable.
install -d -o www-data -g www-data -m 750 "$TRAFFIC_DIR"
install -d -o root -g root -m 755 "$STATE_DIR"
echo "   $TRAFFIC_DIR and $STATE_DIR ready"

say "5. The job and its timer"
install -m 755 "$REPO/bin/swanpan-traffic" /usr/local/bin/swanpan-traffic
install -m 644 "$REPO/nginx/systemd/swanpan-traffic.service" /etc/systemd/system/
install -m 644 "$REPO/nginx/systemd/swanpan-traffic.timer"   /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now swanpan-traffic.timer >/dev/null
echo "   timer: $(systemctl is-active swanpan-traffic.timer)"
systemctl list-timers swanpan-traffic.timer --no-pager | sed -n 2p | sed 's/^/   /'

say "6. Check the product vhosts use the swanpan log format"
# This is the ONE place this installer reads the product configs. It reports;
# it does not edit. Changing a product vhost from here would be a surprise.
for v in swanpan-prod swanpan-staging hoyoul-prod; do
  f=/etc/nginx/sites-available/$v
  [[ -f $f ]] || continue
  if grep -q 'access_log.*swanpan' "$f"; then
    echo "   OK       $v uses swanpan format"
  else
    echo "   MANUAL   $v does not use the swanpan log format."
    echo "            Add: access_log /var/log/nginx/$v.access.log swanpan buffer=32k flush=5s;"
  fi
done

say "7. Basic auth"
if [[ -f $HTPASSWD ]]; then
  echo "   existing $HTPASSWD kept"
else
  PW=$(LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 24)
  install -m 640 -o root -g www-data /dev/null "$HTPASSWD"
  # -b: password on the command line. It is visible in this process's argv
  # for a moment; the alternative (stdin) still ends up in shell history here.
  htpasswd -b "$HTPASSWD" "$AUTH_USER" "$PW" >/dev/null
  echo "   generated credentials -- SAVE THESE, only the hash is stored:"
  echo
  echo "       user:     $AUTH_USER"
  echo "       password: $PW"
  echo
fi

say "8. The analytics vhost"
install -m 644 "$REPO/nginx/analytics.limeyeti.com" /etc/nginx/sites-available/$DOMAIN
ln -sfn /etc/nginx/sites-available/$DOMAIN /etc/nginx/sites-enabled/$DOMAIN
echo "   linked into sites-enabled"

say "9. Certificate"
if [[ -f /etc/letsencrypt/live/$DOMAIN/fullchain.pem ]]; then
  echo "   existing: $(openssl x509 -enddate -noout -in /etc/letsencrypt/live/$DOMAIN/cert.pem)"
else
  echo "   none yet -- issuing via webroot"
  mkdir -p /var/www/html/.well-known/acme-challenge
  # The vhost must be live for validation to succeed, so test and reload with
  # the certificate lines temporarily absent is not possible; nginx -t would
  # fail. Instead: run certonly in --standalone only if webroot cannot work.
  if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx
    certbot certonly --webroot -w /var/www/html -d "$DOMAIN" \
      --non-interactive --agree-tos --register-unsafely-without-email || {
        echo "   webroot failed; trying standalone (stops nginx briefly)"
        systemctl stop nginx
        certbot certonly --standalone -d "$DOMAIN" \
          --non-interactive --agree-tos --register-unsafely-without-email
        systemctl start nginx
      }
  else
    echo "   nginx config invalid; cannot issue. Fix nginx -t first." >&2
    exit 1
  fi
fi

say "10. nginx test and reload"
nginx -t
systemctl reload nginx

say "11. Generate reports once"
systemctl start swanpan-traffic.service
sleep 1
ls -lh "$TRAFFIC_DIR"/*.html 2>/dev/null | sed 's/^/   /' || echo "   no reports yet"

say "Done"
echo "   https://$DOMAIN/   (basic auth)"
echo
echo "   If '/'\'' returns 404 while /index.html works, the cause is almost"
echo "   always alias-vs-root -- see README trap 6."
